"""Application configuration, loaded from environment variables / .env."""
from __future__ import annotations

from functools import lru_cache
from pathlib import Path

from pydantic import Field, model_validator
from pydantic_settings import BaseSettings, SettingsConfigDict

BACKEND_DIR = Path(__file__).resolve().parent.parent
ROOT_DIR = BACKEND_DIR.parent


class Settings(BaseSettings):
    model_config = SettingsConfigDict(
        env_file=(str(ROOT_DIR / ".env"),), env_file_encoding="utf-8", extra="ignore"
    )

    app_env: str = "development"  # development | test | production
    public_base_url: str = "http://localhost:8000"
    database_url: str = f"sqlite:///{(BACKEND_DIR / 'data' / 'flowforge.db').as_posix()}"

    # Fernet key (urlsafe base64, 32 bytes). Generated by scripts/ensure_env.py.
    credentials_encryption_key: str = ""

    # Sessions
    session_ttl_hours: int = 72
    cookie_secure: bool = False
    cors_origins: str = "http://localhost:5173"

    # Demonstration environment (public demo login + seeded, labelled records)
    demo_mode_enabled: bool = True

    # Background worker
    worker_enabled: bool = True  # run worker + scheduler threads inside the API process
    worker_concurrency: int = 4
    worker_poll_seconds: float = 0.5
    # Longer than the largest node timeout (300s), so a slow node is never mistaken for a dead worker.
    stale_execution_seconds: int = 420

    # Execution limits
    max_execution_seconds: int = 300
    max_node_executions: int = 2000
    max_loop_iterations: int = 1000
    max_delay_seconds: int = 300
    max_pending_per_workspace: int = 50
    max_log_value_bytes: int = 32_000

    # HTTP node
    http_max_response_bytes: int = 5_000_000
    http_max_redirects: int = 5
    # Comma separated hostnames/IPs that bypass SSRF checks. Development only;
    # ignored when APP_ENV=production.
    allow_private_http_hosts: str = ""

    # Webhooks
    webhook_max_body_bytes: int = 1_048_576
    webhook_rate_per_minute: int = 60

    # AI
    ai_default_provider: str = ""  # anthropic | openai | gemini; blank = first configured
    ai_timeout_seconds: float = 90.0
    anthropic_api_key: str = Field(default="", repr=False)
    anthropic_model: str = "claude-opus-5-5"
    openai_api_key: str = Field(default="", repr=False)
    openai_model: str = "gpt-4o-mini"
    gemini_api_key: str = Field(default="", repr=False)
    gemini_model: str = "gemini-2.0-flash"

    @property
    def is_production(self) -> bool:
        return self.app_env == "production"

    @property
    def private_host_allowlist(self) -> set[str]:
        if self.is_production:
            return set()
        return {h.strip().lower() for h in self.allow_private_http_hosts.split(",") if h.strip()}

    @model_validator(mode="after")
    def _check_production(self) -> "Settings":
        if self.is_production:
            if not self.credentials_encryption_key:
                raise ValueError("CREDENTIALS_ENCRYPTION_KEY must be set in production")
            if not self.cookie_secure:
                raise ValueError("COOKIE_SECURE must be true in production")
            if self.demo_mode_enabled:
                raise ValueError("DEMO_MODE_ENABLED must be false in production: the demo login is public")
        return self


@lru_cache
def get_settings() -> Settings:
    return Settings()
